import { useMemo, useState } from 'react';
import type { ScanResult } from '../../types';
import { buildFixPlan, downloadBlob, installCommand } from '../../lib/analysis';
import { canPatch, patchManifest } from '../../lib/patch';
import { CommandBox, Empty, SevPill } from './bits';
import { IconArrowRight, IconCopy, IconDownload } from '../Icons';
import { copyText, toast } from '../../lib/toast';

export default function FixPlanView({ result, onOpen }: { result: ScanResult; onOpen: (key: string) => void }) {
  const plan = useMemo(() => buildFixPlan(result), [result]);
  const [excluded, setExcluded] = useState<Set<string>>(new Set());

  const selected = plan.items.filter(i => !excluded.has(i.key));
  const patchable = Boolean(result.manifest) && canPatch(result.fileName);
  const isNpm = result.fileName.toLowerCase() === 'package.json';
  const transitiveCount = selected.filter(i => i.direct === false).length;

  const downloadPatched = () => {
    if (!result.manifest) return;
    try {
      const patched = patchManifest(result.fileName, result.manifest, selected);
      downloadBlob(patched, result.fileName, isNpm ? 'application/json' : 'text/plain');
      toast(`Patched ${result.fileName} downloaded`);
    } catch {
      toast('Couldn’t patch this manifest — it may not be valid JSON');
    }
  };
  const commands = installCommand(selected);
  const resolved = selected.reduce((n, i) => n + i.resolves.length, 0);

  const toggle = (key: string) => setExcluded(prev => {
    const next = new Set(prev);
    if (next.has(key)) next.delete(key);
    else next.add(key);
    return next;
  });

  if (result.vulnerabilities.length === 0) {
    return <div className="card pad-lg"><Empty title="No fixes needed." body="There is nothing to upgrade right now." /></div>;
  }

  return (
    <div className="stack">
      {plan.items.length > 0 && (
        <section className="card plan-hero">
          <div>
            <p className="eyebrow">Fix plan</p>
            <h3 className="plan-title">
              Upgrade {selected.length} {selected.length === 1 ? 'package' : 'packages'} to resolve {resolved} of {result.vulnerabilities.length} advisories.
            </h3>
            <p className="muted small">
              Each target is the lowest version that clears every fixable advisory for that package. Review major-version jumps before you merge.
            </p>
          </div>
          {commands.length > 0 ? (
            <div className="stack-sm">
              {commands.map(c => <CommandBox key={c} command={c} />)}
              <div className="plan-actions">
                {patchable ? (
                  <>
                    <button className="btn btn-secondary" onClick={downloadPatched}>
                      <IconDownload size={15} /> Download patched {result.fileName}
                    </button>
                    {transitiveCount > 0 && (
                      <span className="muted small">
                        {isNpm
                          ? `${transitiveCount} transitive ${transitiveCount === 1 ? 'fix goes' : 'fixes go'} into npm "overrides".`
                          : `${transitiveCount} transitive ${transitiveCount === 1 ? 'pin is' : 'pins are'} appended at the end.`}
                      </span>
                    )}
                  </>
                ) : (
                  <span className="muted small">
                    {result.manifest
                      ? 'Lockfiles are generated by npm, so run the command above instead of editing it.'
                      : 'Patched manifests are available for scans of package.json or requirements.txt.'}
                  </span>
                )}
              </div>
            </div>
          ) : (
            <p className="muted small">Select at least one package below.</p>
          )}
        </section>
      )}

      {plan.items.length > 0 && (
        <section className="card card-flush">
          <div className="card-head card-head-pad">
            <h3>Upgrades</h3>
            <span className="muted small">{selected.length} of {plan.items.length} selected</span>
          </div>
          <ul className="plan-list">
            {plan.items.map(item => {
              const isOn = !excluded.has(item.key);
              const single = installCommand([item])[0];
              const majorJump = item.current.split('.')[0] !== item.target.split('.')[0];
              return (
                <li key={item.key} className={`plan-row ${isOn ? '' : 'is-off'}`}>
                  <label className="check">
                    <input type="checkbox" checked={isOn} onChange={() => toggle(item.key)} aria-label={`Include ${item.name}`} />
                    <span className="check-box" />
                  </label>
                  <button className="plan-main" onClick={() => onOpen(item.key)}>
                    <span className="plan-name">
                      {item.name}
                      {item.direct === false && <span className="tag">Transitive</span>}
                      {majorJump && <span className="tag tag-warn">Major</span>}
                    </span>
                    <span className="plan-versions mono">
                      {item.current} <IconArrowRight size={13} /> <strong>{item.target}</strong>
                    </span>
                  </button>
                  <span className="plan-meta">
                    <SevPill severity={item.worst} />
                    <span className="muted small">
                      {item.resolves.length} fixed{item.remaining.length > 0 && ` · ${item.remaining.length} remain`}
                    </span>
                  </span>
                  <button className="icon-btn" aria-label={`Copy upgrade command for ${item.name}`} onClick={() => copyText(single, 'Command copied')}>
                    <IconCopy size={15} />
                  </button>
                </li>
              );
            })}
          </ul>
        </section>
      )}

      {plan.unpatched.length > 0 && (
        <section className="card card-flush">
          <div className="card-head card-head-pad">
            <h3>No patch available</h3>
            <span className="muted small">{plan.unpatched.reduce((n, u) => n + u.vulns.length, 0)} advisories</span>
          </div>
          <p className="muted small card-note">
            These have no fixed release yet. Consider replacing the package, pinning away from the affected code path, or watching the advisory.
          </p>
          <ul className="plan-list">
            {plan.unpatched.map(u => (
              <li key={u.key} className="plan-row plan-row-plain">
                <button className="plan-main" onClick={() => onOpen(u.key)}>
                  <span className="plan-name">{u.name}</span>
                  <span className="plan-versions mono">{u.version}</span>
                </button>
                <span className="plan-meta">
                  {u.vulns.slice(0, 3).map(v => <span key={v.id} className="mono small muted">{v.identifier}</span>)}
                  {u.vulns.length > 3 && <span className="muted small">+{u.vulns.length - 3}</span>}
                </span>
              </li>
            ))}
          </ul>
        </section>
      )}
    </div>
  );
}
